def test_record_heads_and_bodies(vectors):
    for v in by_fn(vectors, "record"):
        i, e = v["input"], v["expected"]
        vault_id, record_id = h(i["vault_id"]), h(i["record_id"])
        meta = (i["state"], i["version"], i["schema"], i["epoch"])
        aad = head_aad(vault_id, record_id, *meta)
        assert aad.hex() == e["head_aad"], v["name"]
        fields = [list(pair) for pair in i["fields"]]
        plain = head_plain(h(i["data_key"]), i["kind"], fields)
        assert plain.hex() == e["head_plain"], v["name"]
        assert build_head(h(i["k_record"]), aad, *meta, h(i["head_nonce"]), plain).hex() == e["head"], v["name"]
        assert parse_head_plain(plain) == (h(i["data_key"]), i["kind"], fields)

        baad = body_aad(vault_id, record_id, i["version"], i["schema"], i["kind"])
        assert baad.hex() == e["body_aad"], v["name"]
        payload = i["payload"]
        payload = bytes(n % 253 for n in range(payload["len"])) if isinstance(payload, dict) else h(payload)
        body = b"MVB1" + h(i["body_nonce"]) + seal(h(i["data_key"]), h(i["body_nonce"]), baad, pad_payload(payload))
        if isinstance(e["body"], dict):
            assert {"len": len(body), "sha256": hashlib.sha256(body).hexdigest()} == e["body"], v["name"]
        else:
            assert body.hex() == e["body"], v["name"]
    for v in by_fn(vectors, "tombstone"):
        i, e = v["input"], v["expected"]
        meta = (i["state"], i["version"], i["schema"], i["epoch"])
        aad = head_aad(h(i["vault_id"]), h(i["record_id"]), *meta)
        assert aad.hex() == e["head_aad"]
        head = build_head(h(i["k_record"]), aad, *meta, h(i["head_nonce"]), b"")
        assert head.hex() == e["head"], v["name"]
        assert len(head) == 49 + 16


def test_a_whole_vault_opens_from_python(vectors):
    """What the headless home will do: slot -> master key -> header check -> records."""
    scenarios = by_fn(vectors, "scenario")
    assert len(scenarios) == 3
    for v in scenarios:
        i, store = v["input"], v["expected"]["store"]
        header = json.loads(store["header"])
        secrets = i["test_only_secrets"]
        assert (header["format"], header["version"], header["epoch"]) == ("muse-vault-header", 1, i["epoch"])
        assert hashlib.sha256(header_transcript(header)).hexdigest() == v["expected"]["header_transcript_sha256"]
        vault_id = h(header["vault_id"])
        slots = {(s["kind"], s["label"]): s for s in header["slots"]}

        # The laptop: keystore key -> slot secret -> master key (the header MAC is checked inside).
        laptop = slots[("device", "laptop")]
        vmk = open_slot(header, laptop, keystore_unwrap(h(secrets["laptop_keystore_key"]), h(laptop["keystore_blob"])))
        # The recovery words, in either language, and the passkey give the same master key.
        recovery = slots[("recovery", "")]
        for language in ("english", "chinese_traditional"):
            entropy = words_to_entropy(language, secrets[f"recovery_words_{language}"])
            assert open_slot(header, recovery, entropy) == vmk
            identity = hkdf32(b"", entropy, b"muse-vault/v1/export-x25519")
            assert bech32_encode("age", x25519_public(identity)) == recovery["export_recipient"]
        assert open_slot(header, slots[("prf", "passkey")], h(secrets["prf_output"])) == vmk
        # Confirmed in step 1, kept through the lost-device rotation, reset by new words.
        assert recovery["confirmed"] == {1: 1_800_000_001, 2: 1_800_000_001, 3: 0}[i["epoch"]]

        # The phone is in the vault only until it is reported lost; old words stop working.
        if i["epoch"] == 1:
            phone = slots[("device", "phone")]
            assert open_slot(header, phone, keystore_unwrap(h(secrets["phone_keystore_key"]), h(phone["keystore_blob"]))) == vmk
        else:
            assert ("device", "phone") not in slots
        if "old_recovery_words_english" in secrets:
            with pytest.raises(InvalidTag):
                open_slot(header, recovery, words_to_entropy("english", secrets["old_recovery_words_english"]))
        with pytest.raises(InvalidTag):
            open_slot(header, laptop, bytes(32))
        tampered = json.loads(store["header"])
        tampered["slots"][0]["label"] = "laptop2"
        with pytest.raises(InvalidTag):
            open_slot(tampered, laptop, keystore_unwrap(h(secrets["laptop_keystore_key"]), h(laptop["keystore_blob"])))

        # Retired master keys, sealed under the current one.
        vmks = {header["epoch"]: vmk}
        k_previous = subkey(vmk, vault_id, "previous")
        for entry in header["previous"]:
            aad = b"muse-vault/v1/previous" + vault_id + struct.pack(">QQ", entry["epoch"], header["epoch"])
            vmks[entry["epoch"]] = open_box(k_previous, h(entry["nonce"]), aad, h(entry["sealed"]))
        assert sorted(vmks) == list(range(1, i["epoch"] + 1))

        # Records: content, kind, indexed fields, and the tags the store files them under.
        k_index = subkey(vmk, vault_id, "index")
        for name in ("memory", "token"):
            wanted = i["records"][name]
            stored = store["records"][wanted["id"]]
            got = read_record(vmks, vault_id, wanted["id"], stored)
            assert got == {"kind": wanted["kind"], "fields": wanted["fields"], "payload": h(wanted["payload"]),
                           "version": wanted["version"], "schema": wanted["schema"]}
            assert stored["kind_tag"] == kind_tag(k_index, got["kind"])
            assert stored["index_tags"] == [index_tag(k_index, got["kind"], f, val) for f, val in got["fields"]]
            assert struct.unpack(">Q", h(stored["head"])[17:25])[0] == i["epoch"], "heads are re-wrapped at each rotation"
        deleted = store["records"][i["records"]["deleted"]["id"]]
        assert read_record(vmks, vault_id, i["records"]["deleted"]["id"], deleted) is None
        assert (deleted["kind_tag"], deleted["index_tags"]) == ("", [])
        assert index_tag(k_index, "memory", "topic", normalise_index_value(" ＴＥＡ")) in store["records"][i["records"]["memory"]["id"]]["index_tags"]

    # Rotation re-wraps heads and leaves bodies alone.
    first, second = scenarios[0]["expected"]["store"]["records"], scenarios[1]["expected"]["store"]["records"]
    live = [scenarios[0]["input"]["records"][n]["id"] for n in ("memory", "token")]
    for record_id in live:
        assert first[record_id]["body"] == second[record_id]["body"]
        assert first[record_id]["head"] != second[record_id]["head"]
        assert first[record_id]["kind_tag"] != second[record_id]["kind_tag"]

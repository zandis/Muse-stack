"""The vault format, checked from Python against vectors written by the Rust core.

`core/conformance/rust/vault.json` is generated by `core/tests/vault_vectors.rs`
(not by `scripts/export_conformance.py`). This file re-derives the vectors
with the `cryptography` package and the standard library only, following
`docs/spec/interfaces/vault-format.md`, so the format is not defined by one
implementation. It is also the worked example of what a Python reader for the
headless home has to do: open a device slot with a key file, check the header,
decrypt a record.

XChaCha20-Poly1305 is not offered by `cryptography`; it is built here from
its ChaCha20 and ChaCha20-Poly1305 (the HChaCha20 step, see `_hchacha20`).
Argon2id needs `cryptography` 44 or later built against OpenSSL 3.2 or later;
those vectors are skipped where it is missing.
"""


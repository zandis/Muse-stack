def by_fn(vectors: list[dict], name: str) -> list[dict]:
    found = [v for v in vectors if v["fn"] == name]
    assert found, f"no vectors for {name}"
    return found


def h(text: str) -> bytes:
    return bytes.fromhex(text)


def test_every_vector_kind_is_checked_here(vectors):
    checked = {
        "subkey", "hkdf32", "hmac256", "seal", "slot_key", "slot_wrap", "bucket_size", "head_bucket", "pad_payload",
        "normalise_index_value", "index_tag", "kind_tag", "keyed_ref", "mnemonic", "word_list_sha256",
        "word_check_table", "export_identity", "argon2id", "key_file", "keystore_wrap", "record", "tombstone", "scenario",
    }
    assert {v["fn"] for v in vectors} == checked
    assert len(vectors) == 263


def test_hkdf_and_hmac(vectors):
    for v in by_fn(vectors, "subkey"):
        i = v["input"]
        assert subkey(h(i["vmk"]), h(i["vault_id"]), i["purpose"]).hex() == v["expected"], v["name"]
    for v in by_fn(vectors, "hkdf32"):
        i = v["input"]
        assert hkdf32(h(i["salt"]), h(i["ikm"]), h(i["info"])).hex() == v["expected"], v["name"]
    for v in by_fn(vectors, "hmac256"):
        assert hmac256(h(v["input"]["key"]), h(v["input"]["data"])).hex() == v["expected"]
        assert v["expected"] == "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843"  # RFC 4231


def test_xchacha20_poly1305(vectors):
    # draft-irtf-cfrg-xchacha-03, section 2.2.1: the HChaCha20 test vector.
    key = bytes(range(32))
    nonce = h("000000090000004a0000000031415927")
    assert _hchacha20(key, nonce).hex() == "82413b4227b27bfed30e42508a877d73a0f9e4d58a74a853c12ec41326d3ecdc"
    for v in by_fn(vectors, "seal"):
        i = v["input"]
        boxed = seal(h(i["key"]), h(i["nonce"]), h(i["aad"]), h(i["plaintext"]))
        assert boxed.hex() == v["expected"], v["name"]
        assert open_box(h(i["key"]), h(i["nonce"]), h(i["aad"]), boxed) == h(i["plaintext"])
        with pytest.raises(InvalidTag):
            open_box(h(i["key"]), h(i["nonce"]), h(i["aad"]) + b"x", boxed)


def test_slot_keys_and_wraps(vectors):
    for v in by_fn(vectors, "slot_key"):
        i = v["input"]
        private = slot_private(h(i["secret"]), h(i["vault_id"]), i["kind"])
        assert {"private": private.hex(), "public": x25519_public(private).hex()} == v["expected"], v["name"]
    for v in by_fn(vectors, "slot_wrap"):
        i, e = v["input"], v["expected"]
        assert x25519_public(h(i["eph"])).hex() == e["eph_public"], v["name"]
        vmk = unwrap_from_slot(h(i["slot_private"]), h(e["eph_public"]), h(i["nonce"]), h(i["aad"]), h(e["wrapped"]))
        assert vmk.hex() == i["vmk"], v["name"]
        # And the sender's side: the same box from the ephemeral secret and the slot's public key.
        shared = X25519PrivateKey.from_private_bytes(h(i["eph"])).exchange(X25519PublicKey.from_public_bytes(h(i["slot_public"])))
        kek = hkdf32(h(e["eph_public"]) + h(i["slot_public"]), shared, b"muse-vault/v1/slot-kek")
        assert seal(kek, h(i["nonce"]), h(i["aad"]), h(i["vmk"])).hex() == e["wrapped"]


def test_padding(vectors):
    (v,) = by_fn(vectors, "bucket_size")
    assert [bucket_size(n) for n in v["input"]] == v["expected"]
    (v,) = by_fn(vectors, "head_bucket")
    assert [head_bucket(n) for n in v["input"]] == v["expected"]
    for v in by_fn(vectors, "pad_payload"):
        padded = pad_payload(h(v["input"]["payload"]))
        got = {"len": len(padded), "sha256": hashlib.sha256(padded).hexdigest(), "first8": padded[:8].hex()}
        assert got == v["expected"], v["name"]
        assert unpad_payload(padded) == h(v["input"]["payload"])



def _argon2id(passphrase: bytes, salt: bytes, m_kib: int, t: int, p: int) -> bytes:
    try:
        from cryptography.hazmat.primitives.kdf.argon2 import Argon2id
    except ImportError:
        pytest.skip("this cryptography has no Argon2id")
    try:
        return Argon2id(salt=salt, length=32, iterations=t, lanes=p, memory_cost=m_kib).derive(passphrase)
    except Exception as exc:  # UnsupportedAlgorithm when OpenSSL is too old
        if type(exc).__name__ == "UnsupportedAlgorithm":
            pytest.skip("this OpenSSL has no Argon2id")
        raise


# ---------------------------------------------------------------- primitives


def hkdf32(salt: bytes, ikm: bytes, info: bytes) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=salt, info=info).derive(ikm)


def hmac256(key: bytes, data: bytes) -> bytes:
    return hmac.new(key, data, hashlib.sha256).digest()


def _hchacha20(key: bytes, nonce16: bytes) -> bytes:
    """HChaCha20 from the ChaCha20 block function: a keystream block is the
    final state plus the initial state, so subtracting the known initial words
    (the constants and the 16 nonce bytes) gives the words HChaCha20 outputs."""
    block = Cipher(algorithms.ChaCha20(key, nonce16), mode=None).encryptor().update(bytes(64))
    words = struct.unpack("<16I", block)
    initial = struct.unpack("<4I", b"expand 32-byte k") + struct.unpack("<4I", nonce16)
    picked = words[0:4] + words[12:16]
    return struct.pack("<8I", *((w - i) & 0xFFFFFFFF for w, i in zip(picked, initial, strict=True)))


def seal(key: bytes, nonce: bytes, aad: bytes, plaintext: bytes) -> bytes:
    assert len(key) == 32 and len(nonce) == 24
    return ChaCha20Poly1305(_hchacha20(key, nonce[:16])).encrypt(bytes(4) + nonce[16:], plaintext, aad)


def open_box(key: bytes, nonce: bytes, aad: bytes, boxed: bytes) -> bytes:
    return ChaCha20Poly1305(_hchacha20(key, nonce[:16])).decrypt(bytes(4) + nonce[16:], boxed, aad)


def subkey(vmk: bytes, vault_id: bytes, purpose: str) -> bytes:
    return hkdf32(vault_id, vmk, b"muse-vault/v1/key/" + purpose.encode())


def x25519_public(private: bytes) -> bytes:
    return X25519PrivateKey.from_private_bytes(private).public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def slot_private(secret: bytes, vault_id: bytes, kind: str) -> bytes:
    return hkdf32(vault_id, secret, b"muse-vault/v1/slot-x25519/" + kind.encode())


def unwrap_from_slot(private: bytes, eph_public: bytes, nonce: bytes, aad: bytes, wrapped: bytes) -> bytes:
    shared = X25519PrivateKey.from_private_bytes(private).exchange(X25519PublicKey.from_public_bytes(eph_public))
    kek = hkdf32(eph_public + x25519_public(private), shared, b"muse-vault/v1/slot-kek")
    return open_box(kek, nonce, aad, wrapped)


def lp16(data: bytes) -> bytes:
    return struct.pack(">H", len(data)) + data


def lp32(data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + data


def bucket_size(n: int) -> int:
    size = 256
    while size < n and size < 65536:
        size *= 2
    return size if n <= size else -(-n // 65536) * 65536


def head_bucket(n: int) -> int:
    return max(-(-max(n, 1) // 64), 2) * 64


def pad_payload(payload: bytes) -> bytes:
    body = struct.pack(">I", len(payload)) + payload
    return body + bytes(bucket_size(len(body)) - len(body))


def unpad_payload(padded: bytes) -> bytes:
    (n,) = struct.unpack(">I", padded[:4])
    assert len(padded) == bucket_size(n + 4) and not any(padded[4 + n :])
    return padded[4 : 4 + n]


def normalise_index_value(value: str) -> str:
    folded = unicodedata.normalize("NFKC", value).lower()
    return unicodedata.normalize("NFKC", folded).strip()


def index_tag(k_index: bytes, kind: str, field: str, value: str) -> str:
    message = b"muse-vault/v1/index\0" + lp16(kind.encode()) + lp16(field.encode()) + lp16(value.encode())
    return hmac256(k_index, message)[:16].hex()


def kind_tag(k_index: bytes, kind: str) -> str:
    return hmac256(k_index, b"muse-vault/v1/kind\0" + kind.encode())[:16].hex()


def keystore_unwrap(key: bytes, blob: bytes) -> bytes:
    k_wrap = hkdf32(b"", key, b"muse-vault/v1/keystore/wrap")
    return open_box(k_wrap, blob[:24], b"muse-vault/v1/keystore", blob[24:])


def keystore_wrap(key: bytes, secret: bytes) -> bytes:
    nonce = hmac256(hkdf32(b"", key, b"muse-vault/v1/keystore/nonce"), secret)[:24]
    return nonce + seal(hkdf32(b"", key, b"muse-vault/v1/keystore/wrap"), nonce, b"muse-vault/v1/keystore", secret)


# ---------------------------------------------------------------- mnemonics


def _wordlist(language: str) -> list[str]:
    return (WORDLISTS / f"{language}.txt").read_text(encoding="utf-8").split("\n")[:-1]


def entropy_to_indices(entropy: bytes) -> list[int]:
    bits = "".join(f"{b:08b}" for b in entropy) + f"{hashlib.sha256(entropy).digest()[0]:08b}"[: len(entropy) // 4]
    return [int(bits[i : i + 11], 2) for i in range(0, len(bits), 11)]


def entropy_to_words(language: str, entropy: bytes) -> str:
    words = _wordlist(language)
    separator = "　" if language == "japanese" else " "
    return separator.join(unicodedata.normalize("NFC", words[i]) for i in entropy_to_indices(entropy))


def words_to_entropy(language: str, text: str) -> bytes:
    index = {unicodedata.normalize("NFKD", w): i for i, w in enumerate(_wordlist(language))}
    tokens = unicodedata.normalize("NFKD", text).split()
    if language == "chinese_traditional":
        tokens = [ch for token in tokens for ch in token]
    bits = "".join(f"{index[t]:011b}" for t in tokens)
    split = len(bits) * 32 // 33
    entropy = int(bits[:split], 2).to_bytes(split // 8, "big")
    assert f"{hashlib.sha256(entropy).digest()[0]:08b}"[: len(bits) - split] == bits[split:], "checksum"
    return entropy


_BECH32 = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"


def bech32_encode(hrp: str, data: bytes) -> str:
    def polymod(values: list[int]) -> int:
        chk = 1
        for v in values:
            top = chk >> 25
            chk = (chk & 0x1FFFFFF) << 5 ^ v
            for i, g in enumerate((0x3B6A57B2, 0x26508E6D, 0x1EA119FA, 0x3D4233DD, 0x2A1462B3)):
                chk ^= g if (top >> i) & 1 else 0
        return chk

    acc = bits = 0
    five: list[int] = []
    for byte in data:
        acc, bits = (acc << 8) | byte, bits + 8
        while bits >= 5:
            bits -= 5
            five.append((acc >> bits) & 31)
    if bits:
        five.append((acc << (5 - bits)) & 31)
    expand = [ord(c) >> 5 for c in hrp] + [0] + [ord(c) & 31 for c in hrp]
    mod = polymod(expand + five + [0] * 6) ^ 1
    checksum = [(mod >> 5 * (5 - i)) & 31 for i in range(6)]
    return hrp + "1" + "".join(_BECH32[d] for d in five + checksum)


# ---------------------------------------------------------------- records and header


def head_aad(vault_id: bytes, record_id: bytes, state: int, version: int, schema: int, epoch: int) -> bytes:
    return b"muse-vault/v1/record-head" + vault_id + record_id + struct.pack(">BQIQ", state, version, schema, epoch)


def body_aad(vault_id: bytes, record_id: bytes, version: int, schema: int, kind: str) -> bytes:
    return b"muse-vault/v1/record-body" + vault_id + record_id + struct.pack(">QI", version, schema) + lp16(kind.encode())


def head_plain(data_key: bytes, kind: str, fields: list[list[str]]) -> bytes:
    body = data_key + lp16(kind.encode()) + struct.pack(">H", len(fields))
    for name, value in fields:
        body += lp16(name.encode()) + lp16(value.encode())
    out = struct.pack(">H", len(body)) + body
    return out + bytes(head_bucket(len(out)) - len(out))


def parse_head_plain(padded: bytes) -> tuple[bytes, str, list[list[str]]]:
    (n,) = struct.unpack(">H", padded[:2])
    body, at = padded[2 : 2 + n], 32
    assert len(padded) == head_bucket(n + 2) and not any(padded[2 + n :])

    def text() -> str:
        nonlocal at
        (size,) = struct.unpack(">H", body[at : at + 2])
        at += 2 + size
        return body[at - size : at].decode()

    kind = text()
    (count,) = struct.unpack(">H", body[at : at + 2])
    at += 2
    fields = [[text(), text()] for _ in range(count)]
    assert at == len(body)
    return body[:32], kind, fields


def build_head(k_record: bytes, aad: bytes, state: int, version: int, schema: int, epoch: int, nonce: bytes, plain: bytes) -> bytes:
    return b"MVH1" + struct.pack(">BQIQ", state, version, schema, epoch) + nonce + seal(k_record, nonce, aad, plain)


SLOT_TEXT_FIELDS_1 = ("id", "kind", "label")
SLOT_TEXT_FIELDS_2 = ("kdf", "public", "eph", "nonce", "wrapped", "keystore_blob", "credential_id", "prf_salt", "issuer")
SLOT_TEXT_FIELDS_3 = ("export_recipient", "check_salt", "check_nonce", "check_box")


def header_transcript(header: dict) -> bytes:
    t = b"muse-vault/v1/header" + struct.pack(">I", header["version"])
    t += lp32(header["format"].encode()) + lp32(header["vault_id"].encode())
    t += struct.pack(">QQQ", header["epoch"], header["created"], header["updated"])
    t += struct.pack(">I", len(header["slots"]))
    for slot in header["slots"]:
        t += b"".join(lp32(slot[f].encode()) for f in SLOT_TEXT_FIELDS_1)
        t += struct.pack(">Q", slot["created"])
        t += b"".join(lp32(slot[f].encode()) for f in SLOT_TEXT_FIELDS_2)
        t += struct.pack(">Q", slot["confirmed"])
        t += b"".join(lp32(slot[f].encode()) for f in SLOT_TEXT_FIELDS_3)
    t += struct.pack(">I", len(header["previous"]))
    for entry in header["previous"]:
        t += struct.pack(">Q", entry["epoch"]) + lp32(entry["nonce"].encode()) + lp32(entry["sealed"].encode())
    return t


def slot_aad(header: dict, slot: dict) -> bytes:
    aad = b"muse-vault/v1/slot" + struct.pack(">I", header["version"]) + bytes.fromhex(header["vault_id"])
    aad += struct.pack(">Q", header["epoch"]) + lp32(bytes.fromhex(slot["id"])) + lp32(slot["kind"].encode())
    return aad + lp32(slot["kdf"].encode()) + lp32(bytes.fromhex(slot["public"]))


def open_slot(header: dict, slot: dict, secret: bytes) -> bytes:
    """The master key from one slot and its 32-byte secret; raises if anything is wrong."""
    vault_id = bytes.fromhex(header["vault_id"])
    private = slot_private(secret, vault_id, slot["kind"])
    if x25519_public(private).hex() != slot["public"]:
        raise InvalidTag
    vmk = unwrap_from_slot(private, bytes.fromhex(slot["eph"]), bytes.fromhex(slot["nonce"]), slot_aad(header, slot), bytes.fromhex(slot["wrapped"]))
    mac = hmac256(subkey(vmk, vault_id, "header-mac"), header_transcript(header)).hex()
    if not hmac.compare_digest(mac, header["mac"]):
        raise InvalidTag
    return vmk


def read_record(vmk_by_epoch: dict[int, bytes], vault_id: bytes, record_id: str, stored: dict) -> dict | None:
    """Decrypts one stored record; None for an (authentic) tombstone."""
    head, rid = bytes.fromhex(stored["head"]), bytes.fromhex(record_id)
    assert head[:4] == b"MVH1"
    state, version, schema, epoch = struct.unpack(">BQIQ", head[4:25])
    k_record = subkey(vmk_by_epoch[epoch], vault_id, "record-wrap")
    plain = open_box(k_record, head[25:49], head_aad(vault_id, rid, state, version, schema, epoch), head[49:])
    if state == 1:
        assert plain == b"" and stored["body"] == ""
        return None
    data_key, kind, fields = parse_head_plain(plain)
    body = bytes.fromhex(stored["body"])
    assert body[:4] == b"MVB1"
    payload = unpad_payload(open_box(data_key, body[4:28], body_aad(vault_id, rid, version, schema, kind), body[28:]))
    return {"kind": kind, "fields": fields, "payload": payload, "version": version, "schema": schema}



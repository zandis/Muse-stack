def test_key_file_opens_with_the_passphrase(vectors):
    (v,) = by_fn(vectors, "key_file")
    file = json.loads(v["input"]["key_file"])
    assert (file["format"], file["version"], file["kdf"]) == ("muse-vault-keyfile", 1, "argon2id")
    assert (file["m_kib"], file["t"], file["p"]) == (19456, 2, 1)
    passphrase = unicodedata.normalize("NFKC", v["input"]["passphrase"]).encode()
    salt = h(file["salt"])
    kek = _argon2id(passphrase, salt, file["m_kib"], file["t"], file["p"])

def test_recovery_word_check_and_export_recipient(vectors):
    for v in by_fn(vectors, "word_check_table"):
        i = v["input"]
        indices = entropy_to_indices(h(i["entropy"]))
        assert indices == i["indices"]
        table = bytearray(12)
        for position, index in enumerate(indices):
            digest = hashlib.sha256(b"muse-vault/v1/word-check\0" + h(i["salt"]) + bytes([position]) + struct.pack(">H", index)).digest()
            table[position // 2] |= (digest[0] & 15) << (4 if position % 2 == 0 else 0)
        assert table.hex() == v["expected"], v["name"]
    for v in by_fn(vectors, "export_identity"):
        identity = hkdf32(b"", h(v["input"]["entropy"]), b"muse-vault/v1/export-x25519")
        assert identity.hex() == v["expected"]["identity_bytes"]
        assert bech32_encode("age", x25519_public(identity)) == v["expected"]["recipient"], v["name"]



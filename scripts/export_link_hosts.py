#!/usr/bin/env python3
"""Write the hosts the app may open, taken from the published catalogue.

The app opens a page outside itself only when it is https and its host is on a
fixed list: the services' own sign-up and key pages, the one-tap sign-in page,
and the three subscription sites. That list is taken here from the published
catalogue (catalogue/catalogue.v1.json, itself built from config/providers.yaml
and config/resources/*.yaml by scripts/publish_catalogue.py, which checks that
every key page is https) and written to one file that both sides of the app
build in:

    app/src/lib/link-hosts.json

- The web front end imports it (src/lib/links.ts).
- The desktop shell compiles it into the binary (crates/home-link, include_str!),
  and its own test derives the list from the catalogue again and compares.

So the list is fixed when the app is built. Nothing the web view sends can add
a host: Rust checks every link against its compiled-in copy.

Rules: https only; exact host names (no wildcard, no port, no user name, no IP
address); lower case; sorted; no duplicates.

Usage:
    python scripts/export_link_hosts.py            # rewrite the file
    python scripts/export_link_hosts.py --check    # exit 1 if it is out of date

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Iterable, Mapping
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "catalogue" / "catalogue.v1.json"
OUT = ROOT / "app" / "src" / "lib" / "link-hosts.json"
DNS_NAME = re.compile(r"^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")


def host_of(url: Any) -> str | None:
    """The host of an https address with no port and no user name, else None."""
    if not isinstance(url, str):
        return None
    try:
        parts = urlsplit(url)
        port = parts.port
    except ValueError:
        return None
    if parts.scheme != "https" or port is not None or parts.username or parts.password or not parts.hostname:
        return None
    host = parts.hostname.lower()
    return host if DNS_NAME.fullmatch(host) else None


def urls_of(doc: Mapping[str, Any]) -> Iterable[str]:
    """Every sign-up, key and sign-in page, and every subscription's own site, in the catalogue."""
    for section in ("ai_services", "other_allowances"):
        for entry in doc.get(section) or []:
            conn = entry.get("connection") or {}
            for name in ("key_url", "auth_url"):
                if conn.get(name):
                    yield conn[name]
    for entry in doc.get("subscriptions") or []:
        web = (entry.get("open") or {}).get("web")  # the web page only; an app's own scheme is never opened this way
        if isinstance(web, Mapping) and web.get("url"):
            yield web["url"]


def hosts(doc: Mapping[str, Any]) -> list[str]:
    found = set()
    for url in urls_of(doc):
        host = host_of(url)
        if host is None:
            raise ValueError(f"not an https address with a plain host: {url!r}")
        found.add(host)
    return sorted(found)


def render(doc: Mapping[str, Any]) -> str:
    out = {
        "about": "Hosts the app may open: https only, exact names. Generated by scripts/export_link_hosts.py from "
                 "catalogue/catalogue.v1.json; do not edit by hand.",
        "catalogue_date": doc.get("catalogue_date"),
        "hosts": hosts(doc),
    }
    return json.dumps(out, indent=2, ensure_ascii=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if the file is out of date")
    args = parser.parse_args(argv)
    text = render(json.loads(CATALOGUE.read_text(encoding="utf-8")))
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if args.check:
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run: python scripts/export_link_hosts.py", file=sys.stderr)
            return 1
        print("link hosts up to date")
        return 0
    if current != text:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
